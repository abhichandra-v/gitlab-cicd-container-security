#!/usr/bin/env bash
# Builds the binary, runs it, exercises every endpoint with curl and writes
# the full transcript (requests, responses, server log, shutdown) to
# docs/evidence/api-smoke.txt.
set -euo pipefail

cd "$(dirname "$0")/.."
out=docs/evidence/api-smoke.txt
port="${PORT:-18080}"
base="http://127.0.0.1:$port"
log="$(mktemp)"

mkdir -p bin docs/evidence
CGO_ENABLED=0 go build -trimpath -o bin/orders-api ./cmd/orders-api

PORT="$port" LOG_LEVEL=debug ./bin/orders-api >"$log" 2>&1 &
pid=$!
trap 'kill "$pid" 2>/dev/null || true; rm -f "$log"' EXIT

for _ in $(seq 1 50); do
  curl -fsS -o /dev/null "$base/healthz" 2>/dev/null && break
  sleep 0.1
done

# call METHOD PATH [JSON]: prints the command, then status line, headers, body
call() {
  local method="$1" path="$2" data="${3:-}"
  if [ -n "$data" ]; then
    printf "\$ curl -i -X %s %s -H 'Content-Type: application/json' -d '%s'\n" "$method" "$base$path" "$data"
    curl -sS -i -X "$method" "$base$path" -H 'Content-Type: application/json' -d "$data"
  else
    printf '$ curl -i -X %s %s\n' "$method" "$base$path"
    curl -sS -i -X "$method" "$base$path"
  fi
  printf '\n'
}

{
  printf '# orders-api endpoint transcript\n'
  printf '# generated by scripts/api-evidence.sh on %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  printf '# %s, commit %s\n\n' "$(go version)" "$(git rev-parse --short HEAD 2>/dev/null || echo unknown)"

  call GET /healthz
  call GET /readyz
  call GET /orders
  call POST /orders '{"customer":"alice","item":"widget","quantity":2}'
  id="$(curl -sS "$base/orders" | sed -n 's/.*"id":"\([^"]*\)".*/\1/p')"
  call GET "/orders/$id"
  call POST /orders '{"customer":"bob","item":"gadget","quantity":1}'
  call GET /orders
  call GET /orders/0000000000000000
  call POST /orders '{"customer":"","item":"widget","quantity":1}'
  call POST /orders '{"customer":"alice","item":"widget","quantity":0}'
  call POST /orders '{not json'
  call DELETE /orders

  printf '# --- scripts/smoke.sh against the same process ---\n'
  bash scripts/smoke.sh "$base"

  printf '\n# --- SIGTERM, then the server log (JSON, one line per event) ---\n'
  kill -TERM "$pid"
  wait "$pid" && printf '# process exit code: 0\n' || printf '# process exit code: %s\n' "$?"
  cat "$log"
} >"$out" 2>&1

printf 'wrote %s (%s lines)\n' "$out" "$(wc -l <"$out")"
