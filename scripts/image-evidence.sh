#!/usr/bin/env bash
# Records what the hardened image contains and proves it runs locked down.
# Writes docs/evidence/image-{history,inspect,contents,run-hardened}.txt.
#   scripts/image-evidence.sh [image]     default orders-api:local
set -euo pipefail

cd "$(dirname "$0")/.."
IMAGE="${1:-${IMAGE:-orders-api:local}}"
ev=docs/evidence
port="${SMOKE_PORT:-18081}"
# Inside the toolbox the published port is on the Docker host, not localhost.
host=127.0.0.1
if [ "${IN_TOOLBOX:-0}" = 1 ]; then host=host.docker.internal; fi

header() { printf '# %s\n# image %s (%s)\n# generated by scripts/image-evidence.sh on %s\n\n' \
  "$1" "$IMAGE" "$(docker image inspect --format '{{.Id}}' "$IMAGE")" "$(date -u +%Y-%m-%dT%H:%M:%SZ)"; }

{
  header 'docker history --no-trunc'
  docker history --no-trunc --format 'table {{.CreatedBy}}\t{{.Size}}' "$IMAGE"
} >"$ev/image-history.txt"

{
  header 'docker inspect (runtime configuration)'
  docker image inspect "$IMAGE" | jq '.[0] | {
    Id, Architecture, Os,
    User: .Config.User,
    Entrypoint: .Config.Entrypoint,
    Cmd: .Config.Cmd,
    Env: .Config.Env,
    ExposedPorts: .Config.ExposedPorts,
    Healthcheck: .Config.Healthcheck,
    WorkingDir: .Config.WorkingDir,
    Layers: .RootFS.Layers
  }'
} >"$ev/image-inspect.txt"

{
  header 'every file in the image filesystem (docker export | tar -tv)'
  printf '# Directories and zero-byte files other than /orders-api are mount points\n'
  printf '# that `docker create` adds to any container; they are not image layers.\n\n'
  cid="$(docker create "$IMAGE")"
  docker export "$cid" | tar -tvf -
  docker rm "$cid" >/dev/null

  printf '\n# No shell: starting one must fail.\n'
  for sh in /bin/sh /bin/bash /busybox; do
    printf '$ docker run --rm --entrypoint %s %s\n' "$sh" "$IMAGE"
    if docker run --rm --entrypoint "$sh" "$IMAGE" 2>&1 | sed 's/^/  /'; then :; fi
  done
} >"$ev/image-contents.txt"

{
  header 'run with a read-only root filesystem, no capabilities, non-root'
  name="orders-api-evidence-$$"
  cmd=(docker run -d --name "$name" --read-only --cap-drop ALL --user 65532:65532
       --security-opt no-new-privileges -p "$port:8080" "$IMAGE")
  printf '$ %s\n' "${cmd[*]}"
  "${cmd[@]}"
  trap 'docker rm -f "$name" >/dev/null 2>&1 || true' EXIT

  for _ in $(seq 1 50); do
    curl -fsS -o /dev/null "http://$host:$port/healthz" 2>/dev/null && break
    sleep 0.2
  done

  printf '\n$ scripts/smoke.sh http://%s:%s\n' "$host" "$port"
  bash scripts/smoke.sh "http://$host:$port"

  printf '\n$ docker exec %s /orders-api healthcheck; echo exit=$?\n' "$name"
  docker exec "$name" /orders-api healthcheck && printf 'exit=0\n'

  printf '\n$ docker inspect: effective security settings of the running container\n'
  docker inspect "$name" | jq '.[0] | {
    User: .Config.User,
    ReadonlyRootfs: .HostConfig.ReadonlyRootfs,
    CapDrop: .HostConfig.CapDrop,
    CapAdd: .HostConfig.CapAdd,
    SecurityOpt: .HostConfig.SecurityOpt,
    Privileged: .HostConfig.Privileged
  }'

  printf '\n$ docker top %s   (process owner as seen by the host)\n' "$name"
  docker top "$name" -eo uid,pid,args

  printf '\n$ docker stop %s   (SIGTERM, graceful shutdown)\n' "$name"
  docker stop "$name" >/dev/null
  printf 'exit code: %s\n' "$(docker inspect --format '{{.State.ExitCode}}' "$name")"
  printf '\n$ docker logs %s\n' "$name"
  docker logs "$name" 2>&1
} >"$ev/image-run-hardened.txt" 2>&1

printf 'wrote %s/image-history.txt image-inspect.txt image-contents.txt image-run-hardened.txt\n' "$ev"
