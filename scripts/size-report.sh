#!/usr/bin/env bash
# Builds the hardened image and the two comparison images, measures them and
# writes docs/evidence/image-size.txt.
#
# Size is measured as the sum of the image's uncompressed layer tarballs, read
# out of `docker save`. That number does not depend on which Docker storage
# backend is in use, unlike `docker images`, which reports compressed content
# on the containerd image store and unpacked layers on overlay2.
set -euo pipefail

cd "$(dirname "$0")/.."
out=docs/evidence/image-size.txt
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

HARDENED=orders-api:size-hardened
DISTROLESS=orders-api:size-distroless
NAIVE=orders-api:size-naive

build() { # tag dockerfile
  docker build --quiet --provenance=false -t "$1" -f "$2" . >/dev/null
}

# Prints "<uncompressed layer bytes> <layer count>" for an image.
measure() {
  local dir="$work/save" total=0 count=0 layer size
  rm -rf "$dir" && mkdir -p "$dir"
  docker save "$1" | tar -x -C "$dir"
  while IFS= read -r layer; do
    if gzip -t "$dir/$layer" 2>/dev/null; then
      size="$(gzip -dc "$dir/$layer" | wc -c)"
    else
      size="$(wc -c <"$dir/$layer")"
    fi
    total=$((total + size))
    count=$((count + 1))
  done < <(jq -r '.[0].Layers[]' "$dir/manifest.json")
  rm -rf "$dir"
  printf '%s %s\n' "$total" "$count"
}

mb() { awk -v b="$1" 'BEGIN { printf "%.2f", b / 1000000 }'; }
mib() { awk -v b="$1" 'BEGIN { printf "%.2f", b / 1048576 }'; }

row() { # label image dockerfile
  local bytes layers
  read -r bytes layers < <(measure "$2")
  printf '%-11s %-28s %12s %9s %9s %7s\n' "$1" "$3" "$bytes" "$(mb "$bytes")" "$(mib "$bytes")" "$layers"
  eval "bytes_$1=$bytes"
}

base_of() { # dockerfile -> last FROM reference (the runtime base)
  grep -E '^FROM ' "$1" | tail -n 1 | awk '{print $2}'
}

echo "building images (the naive one pulls the full Go toolchain image)..." >&2
build "$HARDENED" Dockerfile
build "$DISTROLESS" build/distroless/Dockerfile
build "$NAIVE" build/naive/Dockerfile

{
  printf '# Image size report\n'
  printf '# generated by scripts/size-report.sh on %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  printf '# commit %s, docker %s, linux/%s\n' \
    "$(git rev-parse --short HEAD 2>/dev/null || echo unknown)" \
    "$(docker version --format '{{.Server.Version}}')" \
    "$(docker version --format '{{.Server.Arch}}')"
  printf '#\n'
  printf '# Sizes are UNCOMPRESSED, LOCAL sizes: the sum of each image'"'"'s layer\n'
  printf '# tarballs after decompression, taken from `docker save`. They are not\n'
  printf '# registry (compressed) sizes. MB = 10^6 bytes, MiB = 2^20 bytes.\n\n'

  printf '%-11s %-28s %12s %9s %9s %7s\n' image dockerfile bytes MB MiB layers
  row naive "$NAIVE" build/naive/Dockerfile
  row distroless "$DISTROLESS" build/distroless/Dockerfile
  row hardened "$HARDENED" Dockerfile

  # shellcheck disable=SC2154  # bytes_* are set by row() through eval
  {
    printf '\nratio naive : hardened      %s : 1\n' "$(awk -v a="$bytes_naive" -v b="$bytes_hardened" 'BEGIN { printf "%.1f", a / b }')"
    printf 'reduction                   %s%%\n' "$(awk -v a="$bytes_naive" -v b="$bytes_hardened" 'BEGIN { printf "%.2f", (1 - b / a) * 100 }')"
    printf 'hardened vs distroless      %s bytes smaller\n' "$((bytes_distroless - bytes_hardened))"
    printf 'target (<= 8 MB)            %s\n' "$(awk -v b="$bytes_hardened" 'BEGIN { print (b <= 8000000) ? "met" : "NOT met" }')"
  }

  printf '\n# Binary inside the hardened image\n'
  cid="$(docker create "$HARDENED")"
  docker export "$cid" | tar -tvf - | awk '$1 !~ /^d/ && $3 > 0 {printf "%s %s bytes  %s\n", $1, $3, $6}'
  docker rm "$cid" >/dev/null

  printf '\n# Base images (pinned by digest in the Dockerfiles)\n'
  printf 'build stage (hardened, distroless)  %s\n' "$(grep -E '^FROM ' Dockerfile | head -n 1 | awk '{print $2}')"
  printf 'runtime base, hardened              %s\n' "$(base_of Dockerfile)"
  printf 'runtime base, distroless            %s\n' "$(base_of build/distroless/Dockerfile)"
  printf 'runtime base, naive                 %s\n' "$(base_of build/naive/Dockerfile)"

  printf '\n# Image IDs measured\n'
  for img in "$NAIVE" "$DISTROLESS" "$HARDENED"; do
    printf '%-26s %s\n' "$img" "$(docker image inspect --format '{{.Id}}' "$img")"
  done
} >"$out"

cat "$out"
